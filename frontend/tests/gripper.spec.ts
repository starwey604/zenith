import { test, expect } from '@playwright/test';
test('双用途夹爪：候选、任务、动作、受力预算与手机布局', async ({ page }) => {
  test.setTimeout(120000);
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/gripper.html'); await page.waitForFunction(() => !!window.__gripper?.scene);
  await expect(page.locator('#g-error')).toBeHidden();
  await expect(page.locator('#gap')).toContainText('80 mm');
  await expect(page.locator('#jaw-force')).toHaveText('64.0 N');
  await page.screenshot({ path: '/tmp/zenith-gripper-desktop.png', fullPage: true });
  await page.locator('[data-view="detail"]').click();
  await page.screenshot({ path: '/tmp/zenith-gripper-detail.png' });
  await page.locator('[data-candidate="angular"]').click();
  expect(await page.evaluate(() => window.__gripper.scene!.angularDrive.visible)).toBe(true);
  await page.locator('[data-task="ore"]').click();
  await page.locator('[data-step="1"]').click();
  await expect(page.locator('#gap')).toContainText('65 mm');
  expect(await page.evaluate(() => window.__gripper.scene!.fingers[0].rotation.z)).not.toBe(0);
  await page.screenshot({ path: '/tmp/zenith-gripper-angular-ore.png' });
  await page.locator('[data-task="store"]').click();
  await page.locator('[data-step="4"]').click();
  await expect(page.locator('#gap')).toContainText('112 mm');
  await page.locator('#play').click();
  await expect(page.locator('#play')).toHaveText('暂停');
  await page.waitForTimeout(300); await page.locator('#play').click();
  expect(await page.evaluate(() => window.__gripper.playing())).toBe(false);
  await page.locator('#mass').fill('2.8'); await expect(page.locator('#payload-note')).toContainText('超过 3 kg');
  await page.locator('#offset').fill('0'); await expect(page.locator('#moment')).toHaveText('0.00 N·m');
  await page.locator('[data-candidate="parallel"]').click(); await page.locator('[data-step="3"]').click();
  await page.screenshot({ path: '/tmp/zenith-gripper-store.png' });
  await page.reload(); await page.waitForFunction(() => !!window.__gripper?.scene);
  expect(await page.evaluate(() => window.__gripper.task())).toBe('store');
  expect(await page.evaluate(() => window.__gripper.progress())).toBe(3);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/zenith-gripper-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  expect(errors).toEqual([]);
});
