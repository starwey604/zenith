import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
test('整头接线、支路聚焦、下载与触点联动',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/wiring.html');
 await expect(page.locator('#wiring-svg')).toBeVisible();
 await expect(page.locator('[data-route="AUX"]')).toContainText('LBC3 顶板');
 await expect(page.locator('[data-route="FIRE"]')).toContainText('动力分电＋CAN 分线板');
 await expect(page.locator('[data-route="AUX"] .device-title')).not.toContainText(['电脑支路保护']);
 await page.screenshot({path:'/tmp/zenith-wiring-desktop.png',fullPage:true});
 await page.locator('[data-circuit="AUX"]').click();await page.locator('#focus-route').check();
 await expect(page.locator('#wiring-svg')).toHaveAttribute('viewBox','0 406 1280 198');
 await expect(page.locator('#route-detail')).toContainText('顶板承担');
 await expect(page).toHaveURL(/circuit=AUX&focus=1/);await page.reload();
 await expect(page.locator('[data-circuit="AUX"]')).toHaveAttribute('aria-pressed','true');
 const csvWait=page.waitForEvent('download');await page.locator('#download-csv').click();const csvDownload=await csvWait;
 const csv=await readFile((await csvDownload.path())!,'utf8');expect(csv).toContain('MINIPC_24V');expect(csv.split('\r\n')).toHaveLength(13);
 const svgWait=page.waitForEvent('download');await page.locator('#download-wiring').click();const svgDownload=await svgWait;
 const svgPath=(await svgDownload.path())!;const svg=await readFile(svgPath,'utf8');expect(svg).toContain('<style>');expect(svg).toContain('Mini PC');
 // View the exported file in Chromium, independent of the app stylesheet.
 const exported=await page.context().newPage();await exported.goto(`data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`);
 expect(await exported.locator('parsererror').count()).toBe(0);
 expect(await exported.locator('[data-route="AUX"] .connector rect').evaluate(el=>getComputedStyle(el).stroke)).toBe('rgb(192, 130, 39)');
 await exported.screenshot({path:'/tmp/zenith-wiring-export.png'});await exported.close();
 await page.locator('[data-circuit="REF"]').click();await expect(page.locator('#route-detail')).toContainText('R2/R4');
 await page.locator('[data-circuit="CTRL"]').click();await expect(page.locator('#route-detail')).toContainText('短支线');
 await expect(page.locator('[data-shared-board="power-can"]')).toHaveCount(1);
 await expect(page.locator('[data-shared-board="power-can"]')).toContainText('三路 CAN');
 await expect(page.locator('#route-detail')).toContainText('LBC3只从此板接CAN');
 await expect(page.locator('#wiring-svg')).toHaveAttribute('viewBox','0 66 1280 348');
 await page.locator('#wiring-svg').screenshot({path:'/tmp/zenith-wiring-shared-board.png'});
 await page.locator('[data-circuit="all"]').click();await expect(page.locator('#focus-route')).toBeDisabled();
 await expect(page.locator('#wiring-svg')).toHaveAttribute('viewBox','0 0 1280 940');
 await page.setViewportSize({width:390,height:844});await page.locator('[data-circuit="AUX"]').click();
 await page.screenshot({path:'/tmp/zenith-wiring-mobile.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.locator('#diagram-scroll').evaluate(el=>el.scrollLeft=el.scrollWidth);
 expect(await page.locator('#diagram-scroll').evaluate(el=>el.scrollLeft)).toBeGreaterThan(0);
 await page.locator('.w-contact-links a').filter({hasText:'A1 ·'}).click();
 await expect(page.locator('#selected-name')).toHaveText('MINIPC_24V');await expect(page.locator('#selected-head')).toHaveText('LBC3 顶板 24 V 输入');
 await page.screenshot({path:'/tmp/zenith-dock-minipc.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 expect(errors).toEqual([]);
});
