import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
test('四芯布局、器件说明、SVG导出与移动端',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/protection.html?part=invalid');
 await expect(page.locator('#protection-svg')).toBeVisible();
 await expect(page.locator('[data-pin]')).toHaveCount(8);
 await expect(page.locator('.can.signal[marker-start][marker-end]')).toHaveCount(4);
 await expect(page.locator('#part-detail')).toContainText('TPS26630');
 await expect(page.locator('#discussion .zc-context')).toContainText('protection');
 await page.locator('[data-part="Q2"]').focus();await page.keyboard.press('Enter');
 await expect(page.locator('#part-detail')).toContainText('不串在测速的主供电路径');
 await page.locator('[data-select="CAN"]').click();await expect(page.locator('#part-detail')).toContainText('U2 · TMUX7462F');
 await expect(page.locator('[data-channel]')).toHaveCount(2);
 await expect(page.locator('[data-part="CAN"]')).toContainText('S1');
 await expect(page.locator('[data-part="CAN"]')).toContainText('D2');
 await expect(page).toHaveURL(/part=CAN/);await page.reload();await expect(page.locator('[data-select="CAN"]')).toHaveAttribute('aria-pressed','true');
 await page.locator('[data-select="U1"]').click();
 await page.screenshot({path:'/tmp/zenith-protection-desktop.png',fullPage:true});
 const download=page.waitForEvent('download');await page.locator('#download-board').click();const file=await download;
 expect(file.suggestedFilename()).toBe('zenith-referee-protection-layout.svg');
 const svg=await readFile((await file.path())!,'utf8');expect(svg).toContain('<style>');expect(svg).toContain('marker-end');expect(svg).toContain('TMUX7462F');expect(svg).not.toContain('芯片型号待定');
 const exported=await page.context().newPage();await exported.goto(`data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`);
 await expect(exported.locator('parsererror')).toHaveCount(0);
 expect(await exported.locator('.pcb').evaluate(el=>getComputedStyle(el).fill)).toBe('rgb(237, 245, 241)');
 await exported.screenshot({path:'/tmp/zenith-protection-export.png'});await exported.close();
 await page.setViewportSize({width:390,height:844});await page.locator('[data-select="CAN"]').click();
 await page.waitForTimeout(200);await page.screenshot({path:'/tmp/zenith-protection-mobile.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.locator('.p-scroll').evaluate(el=>el.scrollLeft=el.scrollWidth);expect(await page.locator('.p-scroll').evaluate(el=>el.scrollLeft)).toBeGreaterThan(0);
 await page.getByRole('link',{name:'返回整头裁判四芯路径'}).click();await expect(page.locator('[data-circuit="REF"]')).toHaveAttribute('aria-pressed','true');
 await page.getByRole('link',{name:'头侧保护板',exact:true}).click();await expect(page.locator('#protection-svg')).toBeVisible();
 expect(errors).toEqual([]);
});
